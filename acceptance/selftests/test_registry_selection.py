"""Registry suspension is a reported skip, while required checks still detect violations."""

import json
import shutil
from xml.etree import ElementTree

import pytest

from conftest import STAND_IN, SUITE

pytest_plugins = ["pytester"]

REGISTRY_CHECKS = {
    "test_without_a_registry_release_the_export_date_stands_for_it",
    "test_a_published_registry_release_is_returned",
    "test_a_published_registry_release_is_asked_for_and_named_with_its_date",
    "test_a_cursor_keeps_the_registry_release_it_was_issued_with[pinned-then-not]",
    "test_a_cursor_keeps_the_registry_release_it_was_issued_with[unpinned-then-pinned]",
}
REASON = (
    "registry-release requirement suspended pending sponsor decision "
    "(NCI_SI_ACCEPTANCE_REGISTRY_RELEASE=optional)"
)


@pytest.mark.parametrize(
    ("mode", "run_mode"), [("optional", "fixture"), ("required", "fixture"), ("optional", "live")]
)
def test_registry_checks_skip_only_in_optional_mode(compliant, monkeypatch, mode, run_mode):
    # Given a server that returns unpinned content even when a registry pin is requested,
    # when the real caDSR checks run, optional suspends exactly five in fixture or live mode
    # as ordinary skips; required detects the violation against fixtures.
    monkeypatch.setenv("NCI_SI_ACCEPTANCE_REGISTRY_RELEASE", mode)
    monkeypatch.setenv("NCI_SI_ACCEPTANCE_MODE", run_mode)
    monkeypatch.setenv("NCI_SI_ACCEPTANCE_PROFILE", "unified")
    monkeypatch.setenv("COMPLIANT_SERVER_PROFILE", "unified")
    shutil.rmtree(compliant.path / "fixtures")
    shutil.copytree(SUITE.parent / "fixtures", compliant.path / "fixtures")
    shutil.copy(SUITE / "test_cadsr.py", compliant.path / "tests" / "test_cadsr.py")
    names = {name.partition("[")[0] for name in REGISTRY_CHECKS}
    selected = " or ".join(sorted(names))
    result = compliant.runpytest_subprocess(
        "tests/test_cadsr.py",
        "-k",
        selected,
        "-p",
        STAND_IN,
        "--report=report.json",
        "--disable-warnings",
        "--junitxml=results.xml",
    )
    report = json.loads((compliant.path / "report.json").read_text(encoding="utf-8"))
    found = {node.partition("::")[2]: row for node, row in report["tests"].items()}
    assert set(found) == REGISTRY_CHECKS
    if mode == "optional":
        assert {name: row["outcome"] for name, row in found.items()} == dict.fromkeys(
            REGISTRY_CHECKS, "skipped"
        )
        assert all("not_live_reason" not in row for row in found.values())
        # JUnit is generated by this test's own pytest child.
        skips = ElementTree.parse(compliant.path / "results.xml").findall(  # noqa: S314
            ".//testcase/skipped"
        )
        assert [skip.attrib["message"] for skip in skips] == [REASON] * 5
        result.assert_outcomes(skipped=5)
    else:
        published = found["test_a_published_registry_release_is_asked_for_and_named_with_its_date"]
        assert published["outcome"] == "failed"
        result.stdout.fnmatch_lines(
            ["*assert (named.get(*", "E *AssertionError: assert ('cadsr', None) == *"]
        )
        assert not any(row["outcome"] in ("skipped", "not_live") for row in found.values())
